import streamlit as st
import pandas as pd
import joblib
import os

from dotenv import load_dotenv
from groq import Groq

from reportlab.platypus import SimpleDocTemplate, Paragraph
from reportlab.lib.styles import getSampleStyleSheet


# ==========================================================
# Load Environment Variables
# ==========================================================

load_dotenv()

client = Groq(
    api_key=os.getenv("GROQ_API_KEY")
)


# ==========================================================
# Load Machine Learning Files
# ==========================================================

model = joblib.load("disease_model.pkl")
label_encoder = joblib.load("label_encoder.pkl")
symptom_columns = joblib.load("symptom_columns.pkl")


# ==========================================================
# Streamlit Page Configuration
# ==========================================================

st.set_page_config(
    page_title="Disease Prediction System",
    page_icon="🩺",
    layout="wide"
)


# ==========================================================
# PDF Function
# ==========================================================

def create_pdf(answer):

    pdf = SimpleDocTemplate("Health_Report.pdf")

    styles = getSampleStyleSheet()

    story = []

    story.append(
        Paragraph("AI Health Report", styles["Title"])
    )

    story.append(
        Paragraph(answer.replace("\n", "<br/>"), styles["BodyText"])
    )

    pdf.build(story)


# ==========================================================
# Main Title
# ==========================================================

st.title("🩺 AI Medical Diagnosis Assistant")

st.write(
    "Select your symptoms and click Predict Disease."
)


# ==========================================================
# Symptom Selection
# ==========================================================

selected_symptoms = st.multiselect(
    "Select Symptoms",
    symptom_columns
)


# ==========================================================
# Disease Prediction
# ==========================================================

if st.button("Predict Disease"):

    if len(selected_symptoms) == 0:
        st.warning("Please select at least one symptom.")
        st.stop()


    # Create Input Data

    input_data = pd.DataFrame(
        0,
        index=[0],
        columns=symptom_columns
    )


    # Mark Selected Symptoms

    for symptom in selected_symptoms:
        input_data.loc[0, symptom] = 1


    # Model Prediction

    prediction = model.predict(input_data)


    disease = label_encoder.inverse_transform(
        prediction
    )[0]


    st.success(
        f"### 🩺 Predicted Disease: **{disease}**"
    )


    # ======================================================
    # AI Prompt
    # ======================================================

    prompt = f"""
You are an experienced medical information assistant.

Disease:
{disease}

Symptoms:
{", ".join(selected_symptoms)}

Provide:

## Disease Description
## Common Causes
## Precautions
## Recommended Diet
## Lifestyle Tips
## When to Consult a Doctor

Do not prescribe medicines.
"""


    # ======================================================
    # AI Response
    # ======================================================

    with st.spinner(
        "Generating AI Health Guidance..."
    ):

        response = client.chat.completions.create(

            model="llama-3.3-70b-versatile",

            messages=[
                {
                    "role": "user",
                    "content": prompt
                }
            ],

            temperature=0.3,
            max_tokens=700
        )


    answer = response.choices[0].message.content


    st.markdown("---")

    st.markdown(
        "## 🤖 AI Health Guidance"
    )

    st.markdown(answer)


    st.markdown("---")


    st.info(
        "⚠️ This prediction is generated by a Machine Learning model. "
        "It is only for educational purposes and is not a medical diagnosis."
    )


    # Create PDF

    create_pdf(answer)


    with open(
        "Health_Report.pdf",
        "rb"
    ) as pdf_file:

        st.download_button(

            label="📥 Download PDF Report",

            data=pdf_file,

            file_name="Health_Report.pdf",

            mime="application/pdf"
        )





        
# ==========================================================
# AI Chatbot
# ==========================================================

st.markdown("---")

st.header("💬 Ask AI Anything")


user_question = st.text_input(
    "Ask any question",
    placeholder="Example: What is diabetes?"
)


if st.button("Ask AI"):

    if user_question.strip() == "":
        st.warning("Please enter a question.")
        st.stop()


    with st.spinner("Thinking..."):

        response = client.chat.completions.create(

            model="llama-3.3-70b-versatile",

            messages=[

                {
                    "role": "system",
                    "content": "You are a helpful AI assistant."
                },

                {
                    "role": "user",
                    "content": user_question
                }

            ],

            temperature=0.5,
            max_tokens=700
        )


    st.success("### 🤖 AI Response")

    st.write(
        response.choices[0].message.content
    )